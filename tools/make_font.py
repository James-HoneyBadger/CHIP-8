"""Generate ``chip8/lib/font.inc``: the 4x5 ASCII font the text library draws.

The glyphs are written here as pictures rather than as hex, because a picture is
the only form of this data a person can check by looking at it. Run the tool to
rewrite the include:

    python3 tools/make_font.py

The machine's own font at ``0x50`` is 4x5 in the high nibble of five bytes, so
this one is the same shape and a glyph from either is drawn by the same
``DRW Vx, Vy, 5``. Codes run from 32 to 95 (space to underscore); the text
library folds lowercase down to these and draws ``?`` for anything else.

The font is emitted as two blobs. That is not decoration: a glyph address is
``base + (code - 32) * 5``, and the offset has to fit in one 8-bit register,
because ``ADD I, Vx`` adds a byte and not a word. Fifty-one glyphs is 255 bytes,
so the first blob holds codes 32-82 and the second the rest.
"""

