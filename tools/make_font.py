#: Glyphs per blob: 51 * 5 = 255 bytes, the most one base address can cover.
CHUNK = 51
FIRST_CODE = 32


def encode(glyph: str) -> bytes:
    """One glyph as the five bytes ``DRW`` reads."""

    rows = glyph.split()
    if len(rows) != 5:
        raise SystemExit(f"glyph {glyph!r} does not have five rows")
    out = bytearray()
    for row in rows:
        if len(row) != 4:
            raise SystemExit(f"row {row!r} of {glyph!r} is not four columns")
        value = 0
        for column, pixel in enumerate(row):
            if pixel == "#":
                value |= 0x80 >> column
        out.append(value)
    return bytes(out)


def blob(codes: list[int]) -> list[str]:
    lines: list[str] = []
    for code in codes:
        glyph = chr(code)
        if glyph not in GLYPHS:
            raise SystemExit(f"no glyph for code {code} ({glyph!r})")
        data = encode(GLYPHS[glyph])
        cells = ",".join(f"0x{byte:02X}" for byte in data)
        label = glyph.replace("\\", "backslash")
        lines.append(f"    {cells}   ; {label}")
    return lines


def main() -> None:
    codes = list(range(FIRST_CODE, FIRST_CODE + len(GLYPHS)))
    missing = [chr(code) for code in codes if chr(code) not in GLYPHS]
    if missing:
        raise SystemExit(f"the map has holes: {missing}")

    parts = [
        "; The ASCII font: 4x5 in the high nibble of five bytes a glyph.",
        ";",
        "; Generated by tools/make_font.py -- edit the glyphs there, not here.",
        "; Codes 32-95 only; the text library folds lowercase down to these.",
        "",
    ]
    first, rest = codes[:CHUNK], codes[CHUNK:]
    parts.append(
        f"; Blob A: codes {first[0]}-{first[-1]} "
        f"({len(first)} glyphs, {len(first) * 5} bytes)."
    )
    parts.append(".bytes font_a")
    parts.extend(blob(first))
    parts.append(".end")
    parts.append("")
    if rest:
        parts.append(
            f"; Blob B: codes {rest[0]}-{rest[-1]} "
            f"({len(rest)} glyphs, {len(rest) * 5} bytes)."
        )
        parts.append(".bytes font_b")
        parts.extend(blob(rest))
        parts.append(".end")
        parts.append("")
    parts.append("; The first code blob B holds, so the drawing code has one number")
    parts.append("; to test against rather than two copies of 83.")
    parts.append(".bytes font_split")
    parts.append(f"    {rest[0] if rest else 0}")
    parts.append(".end")
    parts.append("")

    target = Path(__file__).resolve().parents[1] / "chip8" / "lib" / "font.inc"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {target} ({len(codes)} glyphs)")


if __name__ == "__main__":
    main()
